public class ArrayExample3 {
    public static void main(String[] args) {
        
        String[] type = {"정수형 변수", "실수(float)형 변수", "문자형 변수"};

        int a = 10, b = 20; 
        float c = 23.3f;
        String d = "a";

        System.out.println(type[0] + "\n" + "a=" + a + "\t" + "b=" + b + "\n" + type[1] + "\n" + "c=" + c + "\n" + type[2] + "\n" + "d=" + d);

    }
}
